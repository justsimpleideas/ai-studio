// Writes THIRD_PARTY_NOTICES.md: every package that ships inside the app, with
// its license text, plus the native code bundled in the llama.cpp binaries.
//
//   node scripts/third-party-notices.mjs
//
// Shipped means: the production dependency tree (what the installer copies into
// the app) and the packages bundled into the renderer. Run it again whenever
// dependencies change. License texts for the native libraries are kept in
// resources/licenses, taken from the llama.cpp source node-llama-cpp is built from.

import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md')

// Bundled into the renderer by Vite rather than shipped as node_modules.
const RENDERER_BUNDLED = ['react', 'react-dom', 'scheduler']

const NATIVE = [
  { name: 'llama.cpp / ggml', license: 'MIT', file: 'llama.cpp.txt', what: 'the inference engine inside the chat model binaries' },
  { name: 'nlohmann/json', license: 'MIT', file: 'nlohmann-json.txt', what: 'linked into llama-common' },
  { name: 'cpp-httplib', license: 'MIT', file: 'cpp-httplib.txt', what: 'linked into llama-common' },
  { name: 'subprocess.h', license: 'Unlicense (public domain)', file: 'sheredom-subprocess.txt', what: 'linked into llama-common' }
]

// Read from each wheel's metadata. Not distributed with the app: the user
// installs them into their own Python environment for the image engine.
const PYTHON = [
  ['PyTorch (torch)', 'BSD-3-Clause'],
  ['diffusers', 'Apache-2.0'],
  ['transformers', 'Apache-2.0'],
  ['accelerate', 'Apache-2.0'],
  ['safetensors', 'Apache-2.0'],
  ['tokenizers', 'Apache-2.0'],
  ['huggingface_hub', 'Apache-2.0'],
  ['NumPy', 'BSD-3-Clause AND 0BSD AND MIT AND Zlib AND CC0-1.0'],
  ['Pillow', 'MIT-CMU']
]

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i

function licenseText(dir) {
  const names = fs.readdirSync(dir).filter((n) => LICENSE_FILE.test(n)).sort()
  return names.length ? fs.readFileSync(path.join(dir, names[0]), 'utf8').trim() : null
}

function describe(dir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.licenses ?? []).map((l) => l.type).join(' OR ') || 'see text'
  return { name: pkg.name, version: pkg.version, license, text: licenseText(dir) }
}

const tree = JSON.parse(
  execSync('npm ls --omit=dev --all --json --long', { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
)

const packages = new Map()
;(function walk(node) {
  for (const dep of Object.values(node.dependencies ?? {})) {
    if (dep.missing || !dep.path || !fs.existsSync(path.join(dep.path, 'package.json'))) continue
    const info = describe(dep.path)
    const key = `${info.name}@${info.version}`
    if (packages.has(key)) continue
    packages.set(key, info)
    walk(dep)
  }
})(tree)
for (const name of RENDERER_BUNDLED) {
  const dir = path.join(ROOT, 'node_modules', name)
  if (!fs.existsSync(dir)) continue
  const info = describe(dir)
  packages.set(`${info.name}@${info.version}`, info)
}
const list = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))

const fence = (text) => '```text\n' + text.replace(/```/g, "'''") + '\n```'
const lines = []
lines.push('# Third-party notices', '')
lines.push(
  'Local AI Studio is released under the MIT License (see `LICENSE`). It is built on the',
  'open-source software below, whose notices are reproduced here as their licenses require.',
  'This file is generated by `scripts/third-party-notices.mjs`.',
  ''
)

lines.push('## Native code in the chat engine binaries', '')
for (const n of NATIVE) {
  lines.push(`### ${n.name} (${n.license})`, '', `Used for ${n.what}.`, '')
  lines.push(fence(fs.readFileSync(path.join(ROOT, 'resources', 'licenses', n.file), 'utf8').trim()), '')
}

lines.push('## Electron and Chromium', '')
lines.push(
  'The application runs on Electron (MIT), which includes Chromium and Node.js. Their',
  'complete license texts ship with the app as `LICENSE` and `LICENSES.chromium.html` in',
  'the installation folder.',
  ''
)

lines.push(`## npm packages (${list.length})`, '')
lines.push('| Package | Version | License |', '| --- | --- | --- |')
for (const p of list) lines.push(`| ${p.name} | ${p.version} | ${p.license} |`)
lines.push('')
for (const p of list) {
  lines.push(`### ${p.name} ${p.version} (${p.license})`, '')
  lines.push(p.text ? fence(p.text) : `The package does not include a license file; it is published under ${p.license}.`, '')
}

lines.push('## Installed separately, not distributed with the app', '')
lines.push(
  'The image engine runs in a Python environment the user sets up. These packages are',
  'installed there by the user and are not part of this repository or its installer:',
  ''
)
lines.push('| Package | License |', '| --- | --- |')
for (const [name, license] of PYTHON) lines.push(`| ${name} | ${license} |`)
lines.push(
  '',
  'Model weights (GGUF chat models, the image model) are downloaded by the user from their',
  'publishers and are covered by their own licenses. None are included here.',
  ''
)

fs.writeFileSync(OUT, lines.join('\n'))
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${list.length} packages, ${NATIVE.length} native libraries.`)
